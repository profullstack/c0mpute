// An expert is a manifest applied to an ordinary c0mpute chat turn: its system
// prompt replaces the caller's, its preferred models are tried in order (fail
// over on a busy/absent model), and when the person has connected one of the
// MCP plugins the manifest allows, the plugin tool loop runs with only those.
// Inference is billed like any chat (the person's compute balance, else the
// free tier); the Experts subscription is the access fee on top.

import { forwardChat, isPoisonedTurn, type ChatMessage, type ChatRequest, type Upstream } from "../chat/completions";
import type { ExpertManifest } from "./manifest";

export const EXPERT_MODEL_RE = /^expert:([a-z0-9][a-z0-9-]{1,47})$/;

/** "expert:security-analyst" → "security-analyst"; anything else → null. */
export function expertSlugOf(model: unknown): string | null {
  if (typeof model !== "string") return null;
  const m = EXPERT_MODEL_RE.exec(model.trim().toLowerCase());
  return m ? m[1] : null;
}

const IDENTITY =
  "Your replies are generated by an open-weight model on a peer node of the c0mpute peer-to-peer network (c0mpute.com). " +
  "If asked who you are, say you are the {name} expert on c0mpute; do not claim to be a product of the model's original publisher.";

/** The system prompt as sent: the manifest's prompt, the identity note, and the disclaimer rule. */
export function expertSystemPrompt(m: ExpertManifest): string {
  const parts = [m.system_prompt.trim(), IDENTITY.replace("{name}", m.name)];
  if (m.disclaimer) parts.push(`The user always sees this notice next to your answers: "${m.disclaimer}" Do not contradict it.`);
  return parts.join("\n\n");
}

/** Caller system turns and poisoned stub turns dropped; the expert's prompt first. */
export function expertMessages(m: ExpertManifest, messages: ChatMessage[]): ChatMessage[] {
  const turns = messages.filter((x) => x.role !== "system" && !isPoisonedTurn(x));
  return [{ role: "system", content: expertSystemPrompt(m) }, ...turns];
}

/** The ChatRequest for one model of the expert. The caller's max_tokens may lower the manifest's, never raise it. */
export function expertRequest(m: ExpertManifest, req: ChatRequest, model: string): ChatRequest {
  const cap = m.model.max_tokens ?? 1200;
  return {
    model,
    messages: expertMessages(m, req.messages),
    stream: req.stream,
    temperature: m.model.temperature ?? 0.3,
    max_tokens: req.max_tokens ? Math.min(req.max_tokens, cap) : cap,
  };
}

/** Headers every expert answer carries (the disclaimer URI-encoded: headers are latin-1). */
export function expertHeaders(m: ExpertManifest, model?: string): Record<string, string> {
  return {
    "x-c0mpute-expert": `${m.slug}@${m.version}`,
    ...(model ? { "x-c0mpute-model": model } : {}),
    ...(m.disclaimer ? { "x-c0mpute-disclaimer": encodeURIComponent(m.disclaimer) } : {}),
  };
}

/** Is this upstream failure worth trying the next model for? */
function retryable(status: number, type: string): boolean {
  if (!type.includes("json")) return true; // an nginx page: Infernet restarting
  return status >= 500 || status === 404 || status === 408;
}

export type ExpertAttempt = { model: string; status: number | "error"; error?: string };

export class ExpertUnavailable extends Error {
  constructor(
    message: string,
    public status: number,
    public attempts: ExpertAttempt[],
  ) {
    super(message);
  }
}

/**
 * The whole answer, non-streaming, with failover across the preferred models:
 * a busy/absent model (5xx, 404, an nginx page) AND an empty answer (qwen3
 * spending the whole budget thinking) both move on to the next model. A 4xx
 * stops. Every surface (web, API, SSE, MCP, CLI) goes through this, so the
 * answer can be checked before anyone sees it.
 */
export async function expertComplete(
  upstream: Upstream,
  m: ExpertManifest,
  req: ChatRequest,
  signal?: AbortSignal,
  budgetMs = 280_000,
): Promise<{ text: string; model: string; usage?: unknown; attempts: ExpertAttempt[] }> {
  const attempts: ExpertAttempt[] = [];
  // Every try fits in one route's 300 s: the first model gets most of it, a fallback what is left.
  const deadline = Date.now() + budgetMs;
  const models = m.model.prefer.slice(0, 3);
  let lastStatus = 503;
  let lastError = "";
  for (const model of models) {
    if (signal?.aborted) throw new Error("cancelled");
    const left = deadline - Date.now();
    if (left < 15_000) break;
    const timeout = AbortSignal.timeout(Math.min(left, attempts.length === 0 ? 200_000 : left));
    const sig = signal ? AbortSignal.any([timeout, signal]) : timeout;
    let res: Response;
    try {
      res = await forwardChat(upstream, expertRequest(m, { ...req, stream: false }, model), sig);
    } catch (e) {
      if (signal?.aborted) throw e;
      attempts.push({ model, status: "error", error: e instanceof Error ? (e.name === "TimeoutError" ? "timed out" : e.message) : String(e) });
      continue;
    }
    const type = res.headers.get("content-type") ?? "";
    if (!type.includes("json")) {
      await res.body?.cancel().catch(() => {});
      attempts.push({ model, status: res.status, error: "not JSON (network restarting)" });
      lastStatus = 503;
      continue;
    }
    const body = (await res.json().catch(() => ({}))) as { model?: string; usage?: unknown; choices?: { message?: { content?: string } }[]; error?: { message?: string } };
    if (!res.ok) {
      attempts.push({ model, status: res.status, error: body.error?.message });
      lastStatus = res.status;
      lastError = body.error?.message ?? "";
      if (!retryable(res.status, type)) break;
      continue;
    }
    const text = stripThinking(body.choices?.[0]?.message?.content ?? "");
    if (!text) {
      attempts.push({ model, status: res.status, error: "empty answer" });
      lastStatus = 503;
      continue;
    }
    attempts.push({ model, status: res.status });
    return { text, model: body.model ?? model, usage: body.usage, attempts };
  }
  const tried = attempts.map((a) => `${a.model}: ${a.error ?? a.status}`).join("; ");
  throw new ExpertUnavailable(
    lastStatus >= 400 && lastStatus < 500 && lastError ? lastError : `no node could answer right now (${tried}); try again in a minute`,
    lastStatus >= 400 && lastStatus < 500 ? lastStatus : 503,
    attempts,
  );
}

/** Non-streaming answer text, with the same failover (MCP, CLI). */
export async function expertText(upstream: Upstream, m: ExpertManifest, req: ChatRequest, signal?: AbortSignal): Promise<{ text: string; model: string }> {
  const r = await expertComplete(upstream, m, req, signal);
  return { text: r.text, model: r.model };
}

/** qwen3 sometimes leaks a <think> block into content: never show it as the answer. */
export function stripThinking(s: string): string {
  return s.replace(/<think>[\s\S]*?<\/think>\s*/g, "").replace(/^[\s\S]*<\/think>\s*/, "").trim();
}

/** Hosts of the MCP servers this expert may use. */
export function allowedToolHosts(m: ExpertManifest): Set<string> {
  const out = new Set<string>();
  for (const t of m.tools.mcp) {
    try {
      out.add(new URL(t.url).hostname.toLowerCase());
    } catch {}
  }
  return out;
}

/** May a chat plugin at this URL be used by this expert? */
export function pluginAllowed(m: ExpertManifest, pluginUrl: string): boolean {
  try {
    return allowedToolHosts(m).has(new URL(pluginUrl).hostname.toLowerCase());
  } catch {
    return false;
  }
}

/** An OpenAI chat.completion body for a finished answer (plugin path, /ask). */
export function completionBody(m: ExpertManifest, text: string, model: string) {
  return {
    id: `chatcmpl-x${Date.now().toString(36)}`,
    object: "chat.completion",
    created: Math.floor(Date.now() / 1000),
    model,
    choices: [{ index: 0, message: { role: "assistant", content: text }, finish_reason: "stop" }],
    x_c0mpute_expert: { slug: m.slug, version: m.version, disclaimer: m.disclaimer ?? null },
  };
}

/** The same answer as an OpenAI SSE stream (one content chunk, then stop and [DONE]). */
export function completionStream(m: ExpertManifest, text: string, model: string): ReadableStream<Uint8Array> {
  const id = `chatcmpl-x${Date.now().toString(36)}`;
  const created = Math.floor(Date.now() / 1000);
  const enc = new TextEncoder();
  const chunk = (delta: object, finish: string | null) =>
    `data: ${JSON.stringify({ id, object: "chat.completion.chunk", created, model, choices: [{ index: 0, delta, finish_reason: finish }] })}\n\n`;
  return new ReadableStream({
    start(c) {
      c.enqueue(enc.encode(chunk({ role: "assistant", content: text }, null)));
      c.enqueue(enc.encode(chunk({}, "stop").replace(/}\n\n$/, `,"x_c0mpute_expert":${JSON.stringify({ slug: m.slug, version: m.version, disclaimer: m.disclaimer ?? null })}}\n\n`)));
      c.enqueue(enc.encode("data: [DONE]\n\n"));
      c.close();
    },
  });
}
