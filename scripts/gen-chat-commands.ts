#!/usr/bin/env bun
// Regenerate apps/web/src/lib/chat/command-defs.generated.ts (and the TUI's
// verbatim copy) from the markdown files in commands/. Run after adding or
// editing a command: `bun scripts/gen-chat-commands.ts`.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseCommandFile, type CommandDef } from "../apps/web/src/lib/chat/command-registry";

const root = join(import.meta.dir, "..");

export function loadCommandDir(dir = join(root, "commands")): CommandDef[] {
  const defs = readdirSync(dir)
    .filter((f) => f.endsWith(".md") && !/^readme/i.test(f))
    .sort()
    .map((f) => parseCommandFile(readFileSync(join(dir, f), "utf8"), f));
  const seen = new Set<string>();
  for (const d of defs) {
    if (seen.has(d.name)) throw new Error(`duplicate command /${d.name}`);
    seen.add(d.name);
  }
  return defs;
}

export function renderGenerated(defs: CommandDef[]): string {
  return (
    "// GENERATED by scripts/gen-chat-commands.ts from commands/*.md. Do not edit.\n" +
    "// Attribution: commands/analyze.md is adapted from Anthropic's knowledge-work-plugins (Apache-2.0,\n" +
    "// commands/LICENSE-APACHE-2.0.txt); see each file's frontmatter.\n" +
    'import type { CommandDef } from "./command-registry";\n\n' +
    `export const COMMAND_DEFS: CommandDef[] = ${JSON.stringify(defs, null, 2)};\n`
  );
}

export const GENERATED_PATHS = [
  join(root, "apps/web/src/lib/chat/command-defs.generated.ts"),
  join(root, "apps/tui/src/web/command-defs.generated.ts"),
];

if (import.meta.main) {
  const out = renderGenerated(loadCommandDir());
  for (const p of GENERATED_PATHS) writeFileSync(p, out);
  writeFileSync(join(root, "apps/tui/src/web/command-registry.ts"), readFileSync(join(root, "apps/web/src/lib/chat/command-registry.ts"), "utf8"));
  console.log(`wrote ${GENERATED_PATHS.length} files`);
}
